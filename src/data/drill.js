export function drillBankSummary() {
  const byKind = { confusable: 0, passage: 0, collocation: 0 }
  for (const q of drillQuestions) {
    byKind[q.kind] = (byKind[q.kind] || 0) + 1
  }
  return { total: drillQuestions.length, byKind }
}

